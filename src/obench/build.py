"""Building applications with the site's oneAPI toolchain.

Each application provides ``apps/<app>/build.sh``. obench downloads the
source, generates a wrapper script that loads the toolchain and exports the
build settings, then runs it on the login node or submits it to SLURM. The
install prefix gets an ``obench-build.json`` manifest that runs record for
provenance.
"""

import json
import subprocess
from pathlib import Path

from . import fetch, slurm
from .config import ConfigError, env_strings

MANIFEST = "obench-build.json"


def prefix_for(site, app, version):
    return site.path_for("install_root") / app.name / ("%s-%s" % (version, site.toolchain_tag))


def build_info(site, app, version):
    path = prefix_for(site, app, version) / MANIFEST
    if not path.exists():
        return None
    return json.loads(path.read_text())


def build_env(site, app, version, overrides):
    env = dict(env_strings(app.data["build"]["env"]))
    env.update(env_strings(site.app_settings(app.name).get("build_env", {})))
    env.update(overrides)
    return env


def dependency_prefixes(registry, site, app):
    """Expose other apps built with the same toolchain as <APP>_PREFIX."""
    out = {}
    for other in registry.apps.values():
        if other.name == app.name:
            continue
        version = other.version_for(site)
        info = build_info(site, other, version)
        if info:
            out["%s_PREFIX" % other.name.upper().replace("-", "_")] = info["prefix"]
    return out


def generate(registry, site, app, version, overrides, jobs=None, src_dir=None):
    prefix = prefix_for(site, app, version)
    build_dir = site.path_for("build_root") / ("%s-%s-%s" % (app.name, version, site.toolchain_tag))
    src_dir = src_dir or site.path_for("build_root") / "src" / ("%s-%s" % (app.name, version))
    script = app.dir / app.data["build"]["script"]
    if not script.exists():
        raise ConfigError("%s: build script %s not found" % (app.name, script))
    settings = build_env(site, app, version, overrides)
    obench_env = {
        "OBENCH_APP": app.name,
        "OBENCH_VERSION": version,
        "OBENCH_SRC_DIR": str(src_dir),
        "OBENCH_BUILD_DIR": str(build_dir),
        "OBENCH_PREFIX": str(prefix),
        "OBENCH_JOBS": str(jobs or app.data["build"]["jobs"]),
        "OBENCH_GPU_MODE": site.node["gpu_mode"],
        "OBENCH_MPI_GPU_AWARE": "ON" if site.data["mpi"]["gpu_aware"] else "OFF",
    }
    obench_env.update(dependency_prefixes(registry, site, app))
    manifest = {
        "app": app.name, "version": version, "site": site.name,
        "toolchain": site.toolchain_tag, "prefix": str(prefix), "src_dir": str(src_dir),
        "build_env": settings, "setup": site.setup_lines,
    }
    checks = "\n".join(
        'test -e "$OBENCH_PREFIX/%s" || { echo "obench: expected %s after build" >&2; exit 1; }' % (c, c)
        for c in app.data["build"]["check"])
    header = slurm.sbatch_header(site, "obench-build-%s" % app.name, 1,
                                 app.data["build"]["time_limit"], build_dir / "slurm-%j.out")
    text = BUILD_TEMPLATE.format(
        header=header, app=app.name, version=version, site=site.name,
        setup="\n".join(site.setup_lines) or "# (no toolchain setup lines in the site file)",
        obench_env=slurm.export_lines(obench_env),
        settings=slurm.export_lines(settings) or "# (no build settings)",
        helpers=slurm.SHELL_HELPERS,
        script=slurm.quote(script), checks=checks or "# (no install checks)",
        manifest=json.dumps(manifest, indent=2),
    )
    build_dir.mkdir(parents=True, exist_ok=True)
    out = build_dir / "obench-build.sh"
    out.write_text(text)
    out.chmod(0o755)
    return out, prefix


BUILD_TEMPLATE = """#!/bin/bash
{header}
# Generated by obench: build {app} {version} for site {site}.
# Edit apps/{app}/build.sh or the site file instead of this script.
set -eo pipefail
{helpers}

# --- toolchain (site file: [toolchain] setup) ---
{setup}
set -u

# --- obench locations ---
{obench_env}

# --- build settings (app.toml [build.env], site [apps.{app}.build_env], --set) ---
{settings}

mkdir -p "$OBENCH_BUILD_DIR" "$OBENCH_PREFIX"
echo "obench: building {app} {version} in $OBENCH_BUILD_DIR"
bash {script}
{checks}

# --- build manifest (read by 'obench run' for provenance) ---
MANIFEST="$OBENCH_PREFIX/{manifest_name}"
cat > "$MANIFEST.tmp" <<'OBENCH_EOF'
{manifest}
OBENCH_EOF
if command -v python3 >/dev/null 2>&1; then
  COMPILER=$( (icpx --version 2>/dev/null || echo unknown) | head -1)
  python3 - "$MANIFEST.tmp" "$COMPILER" "$(obench_date)" "$(hostname)" <<'OBENCH_PY'
import json, sys
data = json.load(open(sys.argv[1]))
data.update(compiler=sys.argv[2], built=sys.argv[3], host=sys.argv[4])
json.dump(data, open(sys.argv[1], "w"), indent=2)
OBENCH_PY
fi
mv "$MANIFEST.tmp" "$MANIFEST"
echo "obench: {app} {version} installed in $OBENCH_PREFIX"
""".replace("{manifest_name}", MANIFEST)


def build(registry, site, app, version, overrides, submit=False, dry_run=False, jobs=None,
          log=print):
    src_dir = None
    if not dry_run:
        src_dir = fetch.fetch_source(app, version, site, log)
    script, prefix = generate(registry, site, app, version, overrides, jobs, src_dir)
    log("%s %s: build script %s" % (app.name, version, script))
    log("  install prefix: %s" % prefix)
    if dry_run:
        log("  dry run: not executed. Inspect the script, then run 'obench build %s' again "
            "without --dry-run." % app.name)
        return script
    if submit and site.scheduler == "slurm":
        slurm.submit(script, site, log)
        log("  when the job finishes, check %s/%s" % (prefix, MANIFEST))
        return script
    log("  running on this node (use --submit to build on a compute node instead)")
    with open(Path(script).parent / "build.log", "w") as fh:
        proc = subprocess.Popen(["bash", str(script)], stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, text=True)
        for line in proc.stdout:
            fh.write(line)
            log("  | " + line.rstrip())
        proc.wait()
    if proc.returncode != 0:
        raise ConfigError("build of %s %s failed (exit %d); full log: %s"
                          % (app.name, version, proc.returncode, Path(script).parent / "build.log"))
    return script
