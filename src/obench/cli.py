"""Command-line interface: ``obench <command> ...``.

Typical session::

    obench doctor  --site mycluster              # check toolchain, MPI, SLURM
    obench build   gromacs --site mycluster      # build with oneAPI
    obench run     gromacs/benchMEM --site mycluster --nodes 1,2 --dry-run
    obench run     gromacs/benchMEM --site mycluster --nodes 1,2
    obench status  latest --site mycluster
    obench report  latest --site mycluster
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import __version__, build, collect, fetch, run
from .config import ConfigError, Registry

ROOT_ENV = "OBENCH_ROOT"


def find_root():
    if os.environ.get(ROOT_ENV):
        return Path(os.environ[ROOT_ENV])
    here = Path(__file__).resolve()
    for parent in [Path.cwd(), *Path.cwd().parents, *here.parents]:
        if (parent / "apps").is_dir() and (parent / "sites").is_dir():
            return parent
    raise ConfigError("cannot find the obench repository (a directory with apps/ and sites/).\n"
                      "  Run inside the repository or export %s=/path/to/repo" % ROOT_ENV)


def _list_arg(value):
    return [v.strip() for v in value.split(",") if v.strip()]


def _keyvals(items, what):
    out = {}
    for item in items or []:
        if "=" not in item:
            raise ConfigError("%s expects KEY=VALUE, got '%s'" % (what, item))
        key, value = item.split("=", 1)
        out[key.strip()] = value
    return out


def _param_value(text):
    """--set values: keep strings, but turn plain numbers into numbers."""
    for cast in (int, float):
        try:
            return cast(text)
        except ValueError:
            pass
    return text


# --------------------------------------------------------------------------- commands
def cmd_list(reg, args):
    apps = [reg.app(args.app)] if args.app else reg.apps.values()
    if args.markdown:
        print(catalog_markdown(apps))
        return
    for app in apps:
        meta = app.meta
        print("%s  (%s, default version %s)" % (app.name, meta["title"], meta["default_version"]))
        for wl in app.workloads.values():
            m = wl.meta
            pub = " - %s" % m["publisher"] if m["publisher"] else ""
            print("  %-34s %-9s %-6s %-7s %s%s" % (wl.id, m["kind"], m["size"], m["scaling"],
                                                  m["title"], pub))
        print()
    print("Sites: %s" % ", ".join(reg.site_names()))
    print("Details: obench show APP/WORKLOAD")


def catalog_markdown(apps):
    lines = ["# Workload catalog", "",
             "Generated by `obench list --markdown > docs/workloads.md`; edit the workload files, "
             "not this page.", "",
             "Kinds: **bundled** ships with (or is defined by) the application developers; "
             "**published** comes from a benchmark suite or publication; **custom** is defined "
             "in this repository.", ""]
    for app in apps:
        meta = app.meta
        lines += ["## %s %s" % (meta["title"], meta["default_version"]), "", meta["description"], "",
                  "| Workload | Kind | Publisher | Size | Scaling | Metric | Status |",
                  "|---|---|---|---|---|---|---|"]
        for wl in app.workloads.values():
            m = wl.meta
            name = "[`%s`](%s)" % (wl.id, m["reference"]) if m["reference"] else "`%s`" % wl.id
            lines.append("| %s<br>%s | %s | %s | %s | %s | %s (%s) | %s |" % (
                name, m["title"], m["kind"], m["publisher"] or "-", m["size"], m["scaling"],
                wl.metrics["primary"], wl.metrics["unit"] or "-", m["status"]))
        notes = [(wl.id, wl.meta["notes"]) for wl in app.workloads.values() if wl.meta["notes"]]
        if notes:
            lines += ["", "Notes:", ""] + ["- `%s`: %s" % n for n in notes]
        lines.append("")
    return "\n".join(lines)


def cmd_show(reg, args):
    wl = reg.workload(args.workload)
    m, r = wl.meta, wl.run
    print("%s: %s" % (wl.id, m["title"]))
    for key in ("kind", "publisher", "reference", "size", "scaling", "status", "description", "notes"):
        if m.get(key):
            print("  %-12s %s" % (key + ":", m[key]))
    print("  %-12s %s (%s, %s)" % ("metric:", wl.metrics["primary"], wl.metrics["unit"] or "no unit",
                                   "higher is better" if wl.metrics["higher_is_better"] else "lower is better"))
    print("  %-12s nodes %s, devices/node %s, %d rank(s)/device, %d repetitions, time limit %s" % (
        "defaults:", r["nodes"], r["devices_per_node"], r["ranks_per_device"],
        r["repetitions"], r["time_limit"]))
    if wl.params:
        print("  parameters (override with --set NAME=VALUE):")
        for k, v in wl.params.items():
            print("    %-20s %r" % (k, v))
    for item in wl.data["inputs"]:
        print("  input:       %s%s" % (item["url"] or item["path"], "" if item["sha256"] or item["path"]
                                       else "  [checksum not pinned]"))
    print("  command:     %s" % r["command"].strip())
    print("  file:        %s" % wl.path)


def cmd_validate(reg, args):
    problems = 0
    sites = [reg.site(args.site)] if args.site else [reg.site(n) for n in reg.site_names()]
    for app in reg.apps.values():
        try:
            app.hooks
            workloads = app.workloads
        except ConfigError as exc:
            print("FAIL %s\n%s" % (app.name, exc))
            problems += 1
            continue
        if not (app.dir / app.data["build"]["script"]).exists():
            print("FAIL %s: build script %s missing" % (app.name, app.data["build"]["script"]))
            problems += 1
        for wl in workloads.values():
            for site in sites:
                try:
                    version = app.version_for(site)
                    base = run.base_variables(site, wl, version, build.build_info(site, app, version))
                    for case in run.plan_cases(site, wl, log=lambda *_: None):
                        run.render_case(site, wl, case, base, {})
                except ConfigError as exc:
                    print("FAIL %s on site %s: %s" % (wl.id, site.name, exc))
                    problems += 1
                    break
            else:
                pinned = all(i["sha256"] or i["path"] for i in wl.data["inputs"])
                note = "" if pinned else "  (warning: input checksum not pinned)"
                print("ok   %s%s" % (wl.id, note))
    if problems:
        raise ConfigError("%d problem(s) found" % problems)
    print("\nAll configuration files are valid for site(s): %s" % ", ".join(s.name for s in sites))


def cmd_doctor(reg, args):
    site = reg.site(args.site)
    print("Site %s: %d GPU(s)/node x %d tile(s), mode '%s' -> %d device(s)/node, %d cores/node, "
          "scheduler %s" % (site.name, site.node["gpus_per_node"], site.node["tiles_per_gpu"],
                            site.node["gpu_mode"], site.devices_per_node, site.node["cores_per_node"],
                            site.scheduler))
    for key in ("install_root", "build_root", "data_root", "results_root"):
        print("  %-13s %s" % (key, site.path_for(key)))
    probes = [
        ("C compiler (icx)", "icx --version | head -1"),
        ("C++/SYCL compiler (icpx)", "icpx --version | head -1"),
        ("MPI C++ wrapper", "command -v mpiicpx || command -v mpicxx"),
        ("MPI launcher", "command -v mpiexec || command -v srun"),
        ("oneMKL (MKLROOT)", 'test -n "${MKLROOT:-}" && echo "$MKLROOT"'),
        ("CMake", "cmake --version | head -1"),
        ("git", "git --version"),
        ("SYCL devices (sycl-ls)", "sycl-ls"),
    ]
    script = "\n".join(site.setup_lines) + "\nset -o pipefail\n"
    for i, (_, probe) in enumerate(probes):
        script += 'echo "@@%d@@"; ( %s ) 2>&1; echo "@@rc=$?"\n' % (i, probe)
    out = subprocess.run(["bash", "-c", script], capture_output=True, text=True).stdout
    failures = 0
    for i, (name, _) in enumerate(probes):
        chunk = out.split("@@%d@@" % i, 1)[-1].split("@@rc=", 1)
        text, rc = chunk[0].strip(), chunk[1].split()[0] if len(chunk) > 1 else "1"
        ok = rc == "0" and bool(text)
        if name.startswith("SYCL"):
            gpus = [line for line in text.splitlines() if ":gpu" in line]
            ok = bool(gpus)
            text = "\n".join(gpus) or "no GPU visible here (expected on a login node; " \
                                       "run 'obench doctor' inside a compute-node allocation to check GPUs)"
        failures += 0 if ok or name.startswith("SYCL") else 1
        print("%s %s" % ("[ok]     " if ok else "[missing]", name))
        for line in text.splitlines()[:4]:
            print("            %s" % line)
    sched = shutil.which("sbatch")
    if site.scheduler == "slurm":
        print("%s SLURM sbatch" % ("[ok]     " if sched else "[missing]"))
        failures += 0 if sched else 1
    if failures:
        print("\n%d check(s) failed. Fix [toolchain] setup in %s (module load lines or setvars.sh)."
              % (failures, site.path))
        return 1
    print("\nToolchain looks usable. Next: obench build APP --site %s" % site.name)
    return 0


def cmd_fetch(reg, args):
    site = reg.site(args.site)
    if args.all:
        targets = [wl for app in reg.apps.values() for wl in app.workloads.values()]
    else:
        targets = [reg.workload(w) for w in args.workloads]
    if not targets:
        raise ConfigError("name workloads to fetch (APP/WORKLOAD) or use --all")
    for wl in targets:
        fetch.fetch_workload(site, wl, force=args.force)


def cmd_build(reg, args):
    site = reg.site(args.site)
    for name in args.apps:
        app = reg.app(name)
        version = app.version_for(site, args.version)
        build.build(reg, site, app, version, _keyvals(args.set, "--set"), submit=args.submit,
                    dry_run=args.dry_run, jobs=args.jobs)


def cmd_run(reg, args):
    site = reg.site(args.site)
    if args.scheduler:
        site.data["site"]["scheduler"] = args.scheduler
    params = {k: _param_value(v) for k, v in _keyvals(args.set, "--set").items()}
    env = _keyvals(args.env, "--env")
    for ident in args.workloads:
        wl = reg.workload(ident)
        print("%s on %s" % (wl.id, site.name))
        exp_dir, experiment = run.prepare(
            reg, site, wl, nodes=args.nodes, devices=args.devices, reps=args.reps, params=params,
            env=env, version=args.version, dry_run=args.dry_run, label=args.label)
        for case in experiment["cases"]:
            print("  case %-8s %d node(s) x %d device(s) = %d device(s), %d rank(s), %d thread(s)/rank"
                  % (case["name"], case["nodes"], case["devices_per_node"], case["total_devices"],
                     case["ranks"], case["threads_per_rank"]))
        if args.dry_run:
            print("  dry run: job scripts written to %s (not submitted)" % exp_dir)
            print("  inspect e.g. %s" % (exp_dir / experiment["cases"][0]["name"] / "job.sh"))
            continue
        run.submit_experiment(site, exp_dir, experiment)
        print("  experiment: %s\n  next: obench status %s --site %s; obench report %s --site %s"
              % (exp_dir, experiment["id"], site.name, experiment["id"], site.name))


def _experiment(reg, args):
    site = reg.site(args.site) if (args.site or os.environ.get("OBENCH_SITE")) else None
    root = site.path_for("results_root") if site else reg.root / "results"
    return collect.resolve_experiment(root, args.experiment)


def cmd_status(reg, args):
    exp_dir = _experiment(reg, args)
    experiment, rows = collect.status(exp_dir)
    print("%s  (%s)" % (experiment["id"], exp_dir))
    print("  %-10s %-16s %-12s %s" % ("case", "job", "state", "reps done"))
    for name, job, state, done in rows:
        print("  %-10s %-16s %-12s %s" % (name, job, state, done))


def cmd_report(reg, args):
    exp_dir = _experiment(reg, args)
    text, problems, _ = collect.report(reg, exp_dir)
    print(text)
    for row in problems:
        print("  %s rep%d: %s - %s" % (row["case"], row["rep"], row["state"], row["detail"]))
    print("Written: %s, %s, %s" % (exp_dir / "report.md", exp_dir / "results.csv", exp_dir / "results.json"))
    return 1 if problems else 0


def cmd_new(reg, args):
    from . import scaffold
    if args.kind == "app":
        path = scaffold.new_app(reg.root, args.name)
    elif args.kind == "workload":
        path = scaffold.new_workload(reg, args.name)
    else:
        path = scaffold.new_site(reg.root, args.name)
    print("Created %s\nEdit the TODO entries, then run: obench validate" % path)


# --------------------------------------------------------------------------- parser
def make_parser():
    p = argparse.ArgumentParser(
        prog="obench", description="Build and run HPC benchmarks with oneAPI on SLURM GPU clusters.",
        epilog="Most commands need a site: --site NAME (a file sites/NAME.toml) or OBENCH_SITE=NAME.")
    p.add_argument("--version", action="version", version="obench %s" % __version__)
    sub = p.add_subparsers(dest="command", metavar="COMMAND")
    sub.required = True

    def add(name, func, help_text, aliases=()):
        sp = sub.add_parser(name, help=help_text, description=help_text, aliases=list(aliases))
        sp.set_defaults(func=func)
        return sp

    def site_arg(sp):
        sp.add_argument("--site", help="site name (sites/NAME.toml) or path; default $OBENCH_SITE")

    sp = add("list", cmd_list, "list applications and workloads")
    sp.add_argument("app", nargs="?", help="only this application")
    sp.add_argument("--markdown", action="store_true", help="print the catalog as a Markdown page")

    sp = add("show", cmd_show, "show details of one workload")
    sp.add_argument("workload", help="APP/WORKLOAD, e.g. gromacs/benchMEM")

    sp = add("validate", cmd_validate, "check all app, workload and site files")
    site_arg(sp)

    sp = add("doctor", cmd_doctor, "check the site toolchain (compilers, MPI, GPUs, SLURM)")
    site_arg(sp)

    sp = add("fetch", cmd_fetch, "download workload inputs (run on a node with internet access)")
    sp.add_argument("workloads", nargs="*", help="APP/WORKLOAD ...")
    sp.add_argument("--all", action="store_true", help="fetch inputs of every workload")
    sp.add_argument("--force", action="store_true", help="download again even if present")
    site_arg(sp)

    sp = add("build", cmd_build, "build applications with the site toolchain")
    sp.add_argument("apps", nargs="+", help="application names, e.g. gromacs heffte")
    sp.add_argument("--version", dest="version", help="application version (default from site/app)")
    sp.add_argument("--set", action="append", metavar="KEY=VALUE",
                    help="override a build setting from app.toml [build.env] (repeatable)")
    sp.add_argument("-j", "--jobs", type=int, help="parallel compile jobs")
    sp.add_argument("--submit", action="store_true", help="build in a SLURM job instead of on this node")
    sp.add_argument("--dry-run", action="store_true", help="only write the build script")
    site_arg(sp)

    sp = add("run", cmd_run, "generate and submit benchmark jobs")
    sp.add_argument("workloads", nargs="+", help="APP/WORKLOAD ...")
    sp.add_argument("--nodes", type=_list_arg, help="node counts, e.g. 1,2,4")
    sp.add_argument("--devices", type=_list_arg,
                    help="GPU devices per node, e.g. 1,2,4,max (a device is a GPU or a tile, see site gpu_mode)")
    sp.add_argument("--reps", type=int, help="repetitions per case")
    sp.add_argument("--set", action="append", metavar="NAME=VALUE", help="override a workload parameter")
    sp.add_argument("--env", action="append", metavar="NAME=VALUE", help="extra environment variable")
    sp.add_argument("--version", dest="version", help="application version")
    sp.add_argument("--label", help="suffix for the experiment id")
    sp.add_argument("--scheduler", choices=("slurm", "local"),
                    help="override the site scheduler (local = run now inside an allocation)")
    sp.add_argument("--dry-run", action="store_true", help="write job scripts without submitting")
    site_arg(sp)

    for name, func, text, aliases in (
            ("status", cmd_status, "show job state of an experiment", ()),
            ("report", cmd_report, "parse, validate and summarize an experiment", ("collect",))):
        sp = add(name, func, text, aliases)
        sp.add_argument("experiment", nargs="?", default="latest",
                        help="experiment directory, id (or part of it), or 'latest'")
        site_arg(sp)

    sp = add("new", cmd_new, "create a new app, workload or site from a template")
    sp.add_argument("kind", choices=("app", "workload", "site"))
    sp.add_argument("name", help="app: NAME; workload: APP/NAME; site: NAME")
    return p


def main(argv=None):
    args = make_parser().parse_args(argv)
    try:
        reg = Registry(find_root())
        return args.func(reg, args) or 0
    except ConfigError as exc:
        print("obench: error: %s" % exc, file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
